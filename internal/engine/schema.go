// SchemaNames are the schemas EffectiveSchema can produce.
var SchemaNames = []string{"deployment", "tenant", "stack", "users"}

// EffectiveSchema returns the named JSON Schema as an editor should see it: the
// embedded base schema (the contract `mksrv validate` enforces, untouched) with
// the values only the binary knows injected as completions, and a description on
// the fields people look up most (ADR 0045, phase 1).
//
//   - Stack names become real enums, so an editor suggests the catalog and flags a typo:
//     hosts[].stacks gets every stack a host can run, a tenant's stacks the per-tenant
//     ones, and a tenant's local_hosts[].stacks the local-only ones.
//   - instance_type gets the sizes mksrv can plan capacity for, but as `anyOf` with
//     the original pattern, so a type that is not suggested is still accepted.
//
// The base schemas are not rewritten (they are hand-formatted); everything is
// applied to the decoded document, and a path that no longer exists is an error,
// so a schema change that would silently drop a completion fails a test instead.
func EffectiveSchema(name string, catalog map[string]model.Stack) ([]byte, error) {
	raw, err := engineassets.FS.ReadFile("schemas/" + name + ".v1.json")
	if err != nil {
		return nil, fmt.Errorf("unknown schema %q (one of %s)", name, strings.Join(SchemaNames, ", "))
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber() // keep numbers exactly as written
	var doc map[string]any
	if err := dec.Decode(&doc); err != nil {
		return nil, fmt.Errorf("parse schema %s: %w", name, err)
	}

	switch name {
	case "deployment":
		hostStacks, hostDocs := stackEnum(catalog, func(s model.Stack) bool { return !s.LocalHostsOnly })
		if err := setEnum(doc, "/$defs/host/properties/stacks/items", hostStacks, hostDocs); err != nil {
			return nil, err
		}
		if err := suggestInstanceTypes(doc, "/$defs/host/properties/instance_type"); err != nil {
			return nil, err
		}
	case "tenant":
		tenantStacks, tenantDocs := stackEnum(catalog, func(s model.Stack) bool { return s.PerTenant && !s.LocalHostsOnly })
		if err := setEnum(doc, "/properties/stacks/items", tenantStacks, tenantDocs); err != nil {
			return nil, err
		}
		localStacks, localDocs := stackEnum(catalog, func(s model.Stack) bool { return s.LocalHostsOnly })
		if err := setEnum(doc, "/properties/local_hosts/additionalProperties/properties/stacks/items", localStacks, localDocs); err != nil {
			return nil, err
		}
	}
	for path, text := range schemaDescriptions[name] {
		if err := setDescription(doc, path, text); err != nil {
			return nil, err
		}
	}
	doc["$comment"] = "Generated by mksrv from its embedded catalog; regenerate with `mksrv schema " + name + "`. Do not edit."

	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

// stackEnum returns the names of the catalog stacks that pass keep, sorted, and a
// parallel list of one-line descriptions for editors that show them.
func stackEnum(catalog map[string]model.Stack, keep func(model.Stack) bool) ([]any, []any) {
	names := make([]string, 0, len(catalog))
	for name, s := range catalog {
		if keep(s) {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	values := make([]any, len(names))
	docs := make([]any, len(names))
	for i, n := range names {
		values[i] = n
		docs[i] = catalog[n].Title + " — " + catalog[n].Description
	}
	return values, docs
}

// node walks a JSON-pointer-like path (segments separated by "/", no escaping)
// through decoded JSON objects.
func node(doc map[string]any, path string) (map[string]any, error) {
	cur := doc
	for _, seg := range strings.Split(strings.TrimPrefix(path, "/"), "/") {
		next, ok := cur[seg].(map[string]any)
		if !ok {
			return nil, fmt.Errorf("schema path %q: no object at %q", path, seg)
		}
		cur = next
	}
	return cur, nil
}

func setEnum(doc map[string]any, path string, values, descriptions []any) error {
	n, err := node(doc, path)
	if err != nil {
		return err
	}
	if len(values) == 0 {
		return fmt.Errorf("schema path %q: no values to suggest (is the catalog empty?)", path)
	}
	n["enum"] = values
	n["enumDescriptions"] = descriptions // understood by the common YAML/JSON language servers
	delete(n, "pattern")                 // the enum is stricter
	return nil
}

// suggestInstanceTypes offers the sizes mksrv knows without rejecting any other
// type the original pattern accepts.
func suggestInstanceTypes(doc map[string]any, path string) error {
	n, err := node(doc, path)
	if err != nil {
		return err
	}
	pattern, _ := n["pattern"].(string)
	if pattern == "" {
		return fmt.Errorf("schema path %q: expected a pattern to keep", path)
	}
	types := model.SuggestedInstanceTypes()
	values := make([]any, len(types))
	for i, t := range types {
		values[i] = t
	}
	delete(n, "pattern")
	n["anyOf"] = []any{
		map[string]any{"enum": values},
		map[string]any{"pattern": pattern},
	}
	return nil
}

func setDescription(doc map[string]any, path, text string) error {
	n, err := node(doc, path)
	if err != nil {
		return err
	}
	n["description"] = text
	n["markdownDescription"] = text
	return nil
}

